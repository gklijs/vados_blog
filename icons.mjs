// Self-hosts only the Material Design Icons the generated site uses.
//
// vados renders icons as `<em class="mdi mdi-24px mdi-github">`, which needs
// the MDI web font. The full font is ~360 KB (woff2) plus ~50 KB of CSS from a
// CDN, for the dozen or so icons this blog shows. This scans the generated
// HTML for the icons it uses and publishes a subset of the font (a few KB)
// with just their CSS, so no icon can go missing when a page adds a new one.
//
// The font's file name carries a hash of its contents, so netlify.toml can
// cache it forever. The font is Apache-2.0 (its CSS is MIT), so its LICENSE,
// the full Apache-2.0 text (licenses/Apache-2.0.txt) and a NOTICE about the
// subset are published next to it.
//
// Run after `vados generate`. Usage: node icons.mjs [destination]  (default public)

import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import subsetFont from "subset-font";

const require = createRequire(import.meta.url);
const destination = process.argv[2] ?? "public";
const mdiDir = dirname(require.resolve("@mdi/font/package.json"));
const mdiCss = await readFile(join(mdiDir, "css/materialdesignicons.min.css"), "utf8");
const mdiFont = await readFile(join(mdiDir, "fonts/materialdesignicons-webfont.woff2"));
const mdiLicense = await readFile(join(mdiDir, "LICENSE"), "utf8");
const apacheLicense = await readFile(new URL("licenses/Apache-2.0.txt", import.meta.url), "utf8");

async function htmlFiles(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await htmlFiles(path)));
    else if (entry.name.endsWith(".html")) files.push(path);
  }
  return files;
}

const icons = new Set();
const sizes = new Set();
// MDI's non-icon classes; `\d+px` is a size and handled separately.
const utility = /^(?:spin|rotate-\d+|flip-[hv])$/;
for (const file of await htmlFiles(destination)) {
  const html = await readFile(file, "utf8");
  for (const [, classes] of html.matchAll(/\bclass\s*=\s*["']([^"']*)["']/g)) {
    for (const [, name] of classes.matchAll(/\bmdi-([a-z0-9-]+)/g)) {
      if (/^\d+px$/.test(name)) sizes.add(name);
      else if (!utility.test(name)) icons.add(name);
    }
  }
}
if (icons.size === 0) {
  console.error("icons: no mdi-* icon classes found in the generated HTML");
  process.exit(1);
}

const rules = [];
let text = "";
for (const name of [...icons].sort()) {
  const match = mdiCss.match(new RegExp(`\\.mdi-${name}::before\\{content:"\\\\([0-9A-F]+)"\\}`, "i"));
  if (!match) {
    console.error(`icons: mdi-${name} is used but isn't a Material Design Icons icon`);
    process.exit(1);
  }
  text += String.fromCodePoint(parseInt(match[1], 16));
  rules.push(`.mdi-${name}::before{content:"\\${match[1]}"}`);
}
for (const size of [...sizes].sort()) {
  rules.push(`.mdi-${size}.mdi:before{font-size:${size}}`);
}

const subset = await subsetFont(mdiFont, text, { targetFormat: "woff2" });
const hash = createHash("sha256").update(subset).digest("hex").slice(0, 10);
const fontName = `mdi-${hash}.woff2`;

await mkdir(join(destination, "fonts"), { recursive: true });
for (const old of await readdir(join(destination, "fonts"))) {
  if (old.startsWith("mdi-") && old !== fontName) await rm(join(destination, "fonts", old));
}
await writeFile(join(destination, "fonts", fontName), subset);
await writeFile(join(destination, "fonts", "LICENSE"), mdiLicense);
await writeFile(join(destination, "fonts", "LICENSE-2.0.txt"), apacheLicense);
await writeFile(
  join(destination, "fonts", "NOTICE"),
  "Material Design Icons webfont subset\n\n" +
    "This directory contains a subset of the Material Design Icons webfont\n" +
    "(https://materialdesignicons.com), generated by icons.mjs from @mdi/font.\n" +
    "The subset is a modified version of the original font. See LICENSE and\n" +
    "LICENSE-2.0.txt.\n",
);

// `block`: the icons live in a private-use area, so a fallback font has
// nothing sensible to show while this small file loads.
const css =
  "/* Material Design Icons subset, generated from @mdi/font; see /fonts/LICENSE. */\n" +
  `@font-face{font-family:"Material Design Icons";src:url("/fonts/${fontName}") format("woff2");font-weight:normal;font-style:normal;font-display:block}` +
  `.mdi:before{display:inline-block;font:normal normal normal 24px/1 "Material Design Icons";font-size:inherit;text-rendering:auto;line-height:inherit;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}` +
  rules.join("") +
  "\n";
await mkdir(join(destination, "css"), { recursive: true });
await writeFile(join(destination, "css", "icons.css"), css);

console.log(`icons: ${icons.size} icon(s), ${subset.length} bytes in /fonts/${fontName}`);
